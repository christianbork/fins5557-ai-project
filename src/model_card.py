def write_model_card(
    metadata_path: Path = METADATA_PATH, reports_dir: Path = REPORTS_DIR, out_path: Path = MODEL_CARD_PATH
) -> Path:
    meta = json.loads(Path(metadata_path).read_text(encoding="utf-8"))
    fairness = pd.read_csv(Path(reports_dir) / "fairness.csv", keep_default_na=False, na_values=[""])
    out_path.write_text(model_card(meta, fairness), encoding="utf-8")
    return out_path
